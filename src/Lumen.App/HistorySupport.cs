    public static bool IsHistorySwitch(string key) => key.EndsWith(".history") || key.EndsWith(".chart");

    /// <summary>Whether the design draws something that this history switch turns on or off.</summary>
    public static bool Draws(WidgetStyle? style, string key) =>
        !IsHistorySwitch(key) || style is not WidgetStyle s || !drawn.TryGetValue(Settings.Successor(s), out var keys) || keys.Contains(key);
}
